// Command notices writes resources/THIRD_PARTY_NOTICES.txt: the project's own
// license and the licenses of the Go modules compiled into the app. The file
// ships inside the app (MyGo copies resources/ into it), because the BSD and
// Apache licenses of the dependencies require their notices to travel with
// binaries.
//
//	go run ./internal/tools/notices           # write the file
//	go run ./internal/tools/notices -check    # fail if the file is out of date
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outFile = "resources/THIRD_PARTY_NOTICES.txt"

type module struct{ Path, Version, Dir string }

type section struct{ Title, Text string }

// modules lists the modules the main package is built from for macOS arm64,
// except the main module itself, sorted by path.
func modules(root string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-f",
		"{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}{{end}}", ".")
	cmd.Dir = root
	// The notices describe the shipped app (macOS arm64), not this machine.
	cmd.Env = append(os.Environ(), "GOOS=darwin", "GOARCH=arm64", "CGO_ENABLED=0")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w: %s", err, strings.TrimSpace(stderr.String()))
	}
	seen := map[string]bool{}
	var mods []module
	for _, line := range strings.Split(string(out), "\n") {
		f := strings.Split(line, "\t")
		if len(f) != 3 || seen[f[0]] {
			continue
		}
		seen[f[0]] = true
		mods = append(mods, module{Path: f[0], Version: f[1], Dir: f[2]})
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

// licenseNames are the file names a license is looked up under, compared
// without regard to case.
var licenseNames = []string{"license", "license.md", "license.txt", "licence", "copying", "copying.md", "unlicense"}

// collect reads the license file of each module. A module without one is an
// error, so a new dependency cannot slip in unnoticed.
func collect(mods []module) ([]section, error) {
	var out []section
	for _, m := range mods {
		entries, err := os.ReadDir(m.Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.Path, err)
		}
		var text []byte
	find:
		for _, want := range licenseNames {
			for _, e := range entries {
				if !e.IsDir() && strings.EqualFold(e.Name(), want) {
					if text, err = os.ReadFile(filepath.Join(m.Dir, e.Name())); err != nil {
						return nil, fmt.Errorf("%s: %w", m.Path, err)
					}
					break find
				}
			}
		}
		if text == nil {
			return nil, fmt.Errorf("%s %s: no license file found in %s", m.Path, m.Version, m.Dir)
		}
		out = append(out, section{Title: m.Path + " " + m.Version, Text: string(text)})
	}
	return out, nil
}

const rule = "================================================================================\n"

// render formats sections into the notices file.
func render(sections []section) string {
	var b strings.Builder
	b.WriteString("Pokedex and the third-party software compiled into it.\n")
	b.WriteString("Generated by `go run ./internal/tools/notices`; do not edit by hand.\n\n")
	for _, s := range sections {
		b.WriteString(rule + s.Title + "\n" + rule + "\n")
		b.WriteString(strings.TrimSpace(s.Text) + "\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// generate builds the content of the notices file for the module at root:
// the project's own LICENSE, then the dependencies.
func generate(root string) (string, error) {
	own, err := os.ReadFile(filepath.Join(root, "LICENSE"))
	if err != nil {
		return "", err
	}
	mods, err := modules(root)
	if err != nil {
		return "", err
	}
	deps, err := collect(mods)
	if err != nil {
		return "", err
	}
	return render(append([]section{{Title: "Pokedex", Text: string(own)}}, deps...)), nil
}

func main() {
	check := flag.Bool("check", false, "fail if "+outFile+" is out of date instead of writing it")
	flag.Parse()
	want, err := generate(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		have, _ := os.ReadFile(outFile)
		if string(have) != want {
			fmt.Fprintf(os.Stderr, "notices: %s is out of date; run: go run ./internal/tools/notices\n", outFile)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(outFile, []byte(want), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}
